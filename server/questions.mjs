const PAIRS = new Map([...VI_HOP_COM.map((q, i) => [q, EN_HOP_COM[i]]), ...VI_NOI_CHIEN.map((q, i) => [q, EN_NOI_CHIEN[i]])])
/** The English twin of a saved Vietnamese question; anything unknown is returned unchanged. */
export const toEnglish = (q) => PAIRS.get(q) ?? q
const isLunchBox = (k) => /hộp cơm|cặp lồng|giữ nhiệt|lunch ?box|food (jar|carrier)/.test(k)
const isAirFryer = (k) => /nồi chiên|air ?fryer/.test(k)
export function buildQuestions(category, n = 40, lang = 'en') {
  const key = (category || '').toLowerCase(), vi = lang === 'vi'
  const list = isLunchBox(key) ? (vi ? VI_HOP_COM : EN_HOP_COM) : isAirFryer(key) ? (vi ? VI_NOI_CHIEN : EN_NOI_CHIEN) : (vi ? VI_TEMPLATES : EN_TEMPLATES).map((t) => t.replace(/\{c\}/g, category || (vi ? 'sản phẩm' : 'this product')))
  return list.slice(0, n)
}
