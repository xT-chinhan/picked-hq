import { chromium } from 'playwright-core'
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] })
const p = await b.newPage({ viewport: { width: 1600, height: 900 } })
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
await p.goto('http://localhost:5197/'); await p.waitForTimeout(3500)
await p.screenshot({ path: '/tmp/pk1.png' })
await p.keyboard.press('/'); await p.waitForTimeout(400)
await p.keyboard.type('hồ sơ Sunhouse'); await p.keyboard.press('Enter'); await p.waitForTimeout(2500)
await p.keyboard.type('replay Elmich'); await p.keyboard.press('Enter'); await p.waitForTimeout(9000)
await p.screenshot({ path: '/tmp/pk2.png' })
await p.keyboard.press('Escape'); await p.keyboard.press('t'); await p.keyboard.press('p'); await p.waitForTimeout(1500)
await p.screenshot({ path: '/tmp/pk3.png' })
const t0 = Date.now(); const fps = await p.evaluate(() => new Promise((r) => { let n = 0; const s = performance.now(); const f = () => { n++; performance.now() - s < 2000 ? requestAnimationFrame(f) : r(n / 2) }; requestAnimationFrame(f) }))
console.log('fps', fps, 'errors', JSON.stringify(errs.slice(0, 5)))
await b.close()
